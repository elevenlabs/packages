#!/usr/bin/env node

import crypto from 'crypto';
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const workletDir = path.join(__dirname, '../worklets');
const webDir = path.join(__dirname, '../src/platform/web');

/** Creates ts versions of needed js scripts to code so that they can be exported and used during runtime. Automatically run during build */

const worklets = [
  {
    jsFile: 'rawAudioProcessor.js',
    tsFile: 'rawAudioProcessor.generated.ts',
    exportName: 'loadRawAudioProcessor',
    processorName: 'rawAudioProcessor',
    outputDir: webDir,
    importPath: './createWorkletModuleLoader.js',
  },
  {
    jsFile: 'audioConcatProcessor.js',
    tsFile: 'audioConcatProcessor.generated.ts',
    exportName: 'loadAudioConcatProcessor',
    processorName: 'audioConcatProcessor',
    outputDir: webDir,
    importPath: './createWorkletModuleLoader.js',
  },
  {
    jsFile: 'scribeAudioProcessor.js',
    tsFile: 'scribeAudioProcessor.generated.ts',
    exportName: 'loadScribeAudioProcessor',
    processorName: 'scribeAudioProcessor',
    outputDir: webDir,
    importPath: './createWorkletModuleLoader.js',
  }
];

// Hashed with the bare name so rewriting the hashed name back in is idempotent.
function registrationPattern(processorName) {
  return new RegExp(`registerProcessor\\(\\s*(["'])${processorName}(?:@[0-9a-f]*)?\\1`, 'g');
}

function hashWorklet(source, processorName) {
  const normalized = source
    .replace(/\r\n/g, '\n')
    .replace(registrationPattern(processorName), `registerProcessor("${processorName}"`);
  return crypto.createHash('sha256').update(normalized).digest('hex').slice(0, 16);
}

console.log('Generating TypeScript worklet files...');

worklets.forEach(({ jsFile, tsFile, exportName, processorName, outputDir, importPath }) => {
  const jsPath = path.join(workletDir, jsFile);
  const tsPath = path.join(outputDir, tsFile);

  const originalJsContent = fs.readFileSync(jsPath, 'utf8');

  const registrations = originalJsContent.match(registrationPattern(processorName)) ?? [];
  if (registrations.length !== 1) {
    throw new Error(
      `${jsFile} must call registerProcessor("${processorName}", ...) exactly once, found ${registrations.length}`
    );
  }

  const hash = hashWorklet(originalJsContent, processorName);
  const jsContent = originalJsContent.replace(
    registrationPattern(processorName),
    `registerProcessor("${processorName}@${hash}"`
  );
  if (jsContent !== originalJsContent) {
    fs.writeFileSync(jsPath, jsContent);
    console.log(`Updated the processor name in ${jsFile} to ${processorName}@${hash}`);
  }

  const tsContent = `// AUTO-GENERATED BY packages/client/scripts/generateWorklets.js
import { createWorkletModuleLoader } from "${importPath}";

export const ${exportName} = createWorkletModuleLoader(
  "${processorName}",
  "${hash}",
  // language=JavaScript
  \`${jsContent}\`
);
`;

  // Write the TS file
  fs.writeFileSync(tsPath, tsContent);
  console.log(`Generated ${tsFile} from ${jsFile}`);
});

console.log('Worklet generation complete!');
